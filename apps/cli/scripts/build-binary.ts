#!/usr/bin/env bun

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import {
	type EngineTarget,
	engineCompiledBuildConfig,
	engineWorkerHostSources,
	resolveBuildRuntimeSources,
} from "@thinkrail/server/build-support";
import { channel, version } from "@thinkrail/shared/version";
import { windowsFileIdentity, windowsIconPath } from "@thinkrail/shared/windowsIdentity";
import { BINARY_SOURCE_MAP_BASE } from "../src/binarySourceMap";
import { binaryArtifactName, targetsWindows } from "./artifactName";

const cliDir = resolve(import.meta.dir, "..");
const repoRoot = resolve(cliDir, "..", "..");
if (resolve(repoRoot, BINARY_SOURCE_MAP_BASE) !== cliDir) {
	throw new Error(`the binary compiles from ${cliDir}, not ${BINARY_SOURCE_MAP_BASE}`);
}
const webDist = join(repoRoot, "apps", "web", "dist");
const webGeneratedPath = join(cliDir, "src", "web-assets.generated.ts");
const extGeneratedPath = join(cliDir, "src", "bundled-extensions.generated.ts");
const runtimeGeneratedPath = join(cliDir, "src", "runtime-assets.generated.ts");
const workerHostGeneratedPath = join(cliDir, "src", "engine-worker-host.generated.ts");
const generated: Record<string, string> = {};
const entryPath = join(cliDir, "src", "compiled-entry.ts");
const outDir = join(cliDir, "dist");
const runtimeSources = resolveBuildRuntimeSources();

function listFiles(dir: string): string[] {
	const out: string[] = [];
	for (const name of readdirSync(dir)) {
		const full = join(dir, name);
		if (statSync(full).isDirectory()) out.push(...listFiles(full));
		else out.push(full);
	}
	return out;
}

function embedFiles(
	files: { root: string; file: string }[],
	importPrefix: string,
): { imports: string[]; entries: string[]; version: string } {
	const hash = createHash("sha256");
	const imports: string[] = [];
	const entries: string[] = [];
	const seen = new Set<string>();
	files.forEach(({ root, file }, i) => {
		const route = relative(root, file).split(sep).join("/");
		if (seen.has(route)) throw new Error(`duplicate embedded route: ${route}`);
		seen.add(route);
		hash.update(route).update(readFileSync(file));
		imports.push(`import ${importPrefix}${i} from ${JSON.stringify(file)} with { type: "file" };`);
		entries.push(`\t{ route: ${JSON.stringify(route)}, data: ${importPrefix}${i} },`);
	});
	return { imports, entries, version: hash.digest("hex").slice(0, 16) };
}

function generateWebManifest(): void {
	if (!existsSync(join(webDist, "index.html"))) {
		throw new Error(`web build not found at ${webDist} — run \`bun run build:web\` first.`);
	}
	const webFiles = listFiles(webDist).sort();
	const maps = webFiles.filter((file) => file.endsWith(".map"));
	if (maps.length) throw new Error(`refusing to embed web source maps: ${maps.join(", ")}`);
	const files = webFiles.map((file) => ({ root: webDist, file }));
	const { imports, entries, version } = embedFiles(files, "a");
	generated[webGeneratedPath] =
		`// GENERATED by scripts/build-binary.ts — do not edit. Embeds apps/web/dist into the single-file binary.\n${imports.join("\n")}\n\nexport const webAssetsVersion = ${JSON.stringify(version)};\nexport const embeddedWebAssets = [\n${entries.join("\n")}\n];\n`;
}

function generateBundledExtensions(): void {
	const entryPaths = runtimeSources.extensions.map((extension) => extension.entry);
	const factoryImports = entryPaths.map((path, i) => `import x${i} from ${JSON.stringify(path)};`);
	const factoryList = entryPaths.map((_, i) => `x${i}`).join(", ");
	const skillFiles = runtimeSources.skillRoots.flatMap((root) =>
		listFiles(root)
			.sort()
			.map((file) => ({ root, file })),
	);
	const { imports, entries, version } = embedFiles(skillFiles, "s");
	generated[extGeneratedPath] =
		`// GENERATED by scripts/build-binary.ts — do not edit. Value-imports the bundled pi packages and\n// embeds the bundled skills into the single-file binary.\n${factoryImports.join("\n")}\n${imports.join("\n")}\n\nexport const bundledExtensionFactories = [${factoryList}];\nexport const bundledSkillsVersion = ${JSON.stringify(version)};\nexport const embeddedSkillFiles = [\n${entries.join("\n")}\n];\n`;
}

function generateRuntimeManifest(): void {
	const files = [runtimeSources.trashHelpers.macos, runtimeSources.trashHelpers.windows].map(
		(file) => ({ root: dirname(file), file }),
	);
	const { imports, entries, version } = embedFiles(files, "r");
	generated[runtimeGeneratedPath] =
		`// GENERATED by scripts/build-binary.ts — do not edit. Embeds native runtime helper sidecars.\n${imports.join("\n")}\n\nexport const runtimeAssetsVersion = ${JSON.stringify(version)};\nexport const embeddedRuntimeAssets = [\n${entries.join("\n")}\n];\n`;
}

function generateEngineWorkerHost(): void {
	const { cli, workerHost } = engineWorkerHostSources();
	generated[workerHostGeneratedPath] =
		`// GENERATED by scripts/build-binary.ts — do not edit. Routes the engine's worker selectors to its own host.\nexport { declareWorkerHostEntry as declareEngineWorkerHost, isWorkerHostSelector as isEngineWorkerSelector } from ${JSON.stringify(workerHost)};\n\nexport async function runEngineWorker(): Promise<void> {\n\tawait import(${JSON.stringify(cli)});\n}\n`;
}

function isCompileTarget(value: string): value is Bun.Build.CompileTarget {
	return /^bun-(darwin|linux|windows)-(x64|arm64|aarch64)(-(baseline|modern))?(-(glibc|musl))?$/.test(
		value,
	);
}

function engineTarget(target: Bun.Build.CompileTarget | undefined): EngineTarget {
	if (!target) return { platform: process.platform, arch: process.arch };
	const [, os, arch] = target.split("-");
	return {
		platform: os === "windows" ? "win32" : (os ?? process.platform),
		arch: arch === "aarch64" ? "arm64" : (arch ?? process.arch),
	};
}

function windowsMetadata(target: string | undefined): Bun.CompileBuildOptions["windows"] {
	if (!targetsWindows(target)) return undefined;
	if (process.platform !== "win32") {
		console.warn(
			"Windows icon and file properties need a Windows host; this cross-compiled binary keeps Bun's.",
		);
		return undefined;
	}
	const identity = windowsFileIdentity({ version, channel });
	return {
		icon: windowsIconPath,
		title: identity.productName,
		description: identity.productName,
		publisher: identity.companyName,
		copyright: identity.copyright,
		version: identity.fileVersion,
	};
}

const requestedTarget = process.argv
	.find((a) => a.startsWith("--target="))
	?.slice("--target=".length);
if (requestedTarget !== undefined && !isCompileTarget(requestedTarget)) {
	throw new Error(`unsupported compile target: ${requestedTarget}`);
}
const target = requestedTarget;
const outFile = join(outDir, binaryArtifactName(target));

mkdirSync(outDir, { recursive: true });
rmSync(outFile, { force: true });
generateWebManifest();
generateBundledExtensions();
generateRuntimeManifest();
generateEngineWorkerHost();
const engine = await engineCompiledBuildConfig(engineTarget(target));
const windows = windowsMetadata(target);
process.chdir(cliDir);
const result = await Bun.build({
	entrypoints: [entryPath],
	target: "bun",
	format: "esm",
	bytecode: true,
	sourcemap: "linked",
	plugins: engine.plugins,
	define: engine.define,
	external: engine.external,
	files: { ...engine.files, ...generated },
	compile: {
		outfile: outFile,
		autoloadBunfig: false,
		...(target ? { target } : {}),
		...(windows ? { windows } : {}),
	},
	throw: false,
});
if (!result.success) {
	for (const log of result.logs) console.error(log);
	process.exit(1);
}
rmSync(`${outFile}.map`, { force: true });
console.log(`\nBuilt single-file binary: ${outFile}`);
